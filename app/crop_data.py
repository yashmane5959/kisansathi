SUPPORTED_CROPS: List[str] = [crop["canonical_name"] for crop in CROPS_DATA.values()]


def get_crop_data(crop_name: str) -> Optional[Dict[str, Any]]:
    """Look up crop data case-insensitively. Returns None if crop is unsupported."""
    if not crop_name:
        return None
    key = crop_name.strip().lower()
    return CROPS_DATA.get(key)
